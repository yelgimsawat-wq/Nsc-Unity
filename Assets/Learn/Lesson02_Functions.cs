using UnityEngine;

// ============================================================
//  บทที่ 2 : ฟังก์ชันที่รับค่า-ส่งค่ากลับ (Parameter / Return)
// ------------------------------------------------------------
//  วิธีใช้ไฟล์นี้: เหมือนบทที่ 1
//   1. สร้าง Cube ใหม่ (หรือใช้ตัวเดิม)
//   2. ลากไฟล์นี้ไปวางใน Inspector ของ Cube
//   3. เปิด Console แล้วกด Play
// ============================================================

public class Lesson02_Functions : MonoBehaviour
{
    void Start()
    {
        // ---------- ทบทวนจากบทที่แล้ว (2 จุดที่พลาดตอนสอบ) ----------

        // ทบทวน 1: int หาร int -> ตัดทศนิยมทิ้งเสมอ
        int a = 7;
        int b = 2;
        Debug.Log($"int/int: {a} / {b} = {a / b}");            // ได้ 3 ไม่ใช่ 3.5

        float c = (float)a / b;
        Debug.Log($"cast เป็น float ก่อนหาร: {c}");              // ได้ 3.5 ของจริง

        // ทบทวน 2: ลูป <= นับรวมตัวสุดท้ายด้วย
        for (int i = 1; i <= 5; i++)
        {
            Debug.Log($"ลูปทบทวน รอบที่ {i}");                  // พิมพ์ 1,2,3,4,5 (5 ครั้ง)
        }


        // ---------- ส่วนที่ 1 : ฟังก์ชันไม่รับค่า ไม่คืนค่า ----------
        // อันนี้เหมือน Start()/Update() ที่รู้จักอยู่แล้ว
        // ต่างกันตรงที่ Unity ไม่เรียกให้อัตโนมัติ - เราต้องเรียกเอง
        SayHello();


        // ---------- ส่วนที่ 2 : ฟังก์ชันรับค่าเข้า (parameter) ----------
        // Heal(int amount) รับตัวเลขเข้าไปทำงานข้างใน แต่ไม่ส่งอะไรกลับ
        Heal(30);
        Heal(10);


        // ---------- ส่วนที่ 3 : ฟังก์ชันคืนค่ากลับ (return) ----------
        // int -> แปลว่าฟังก์ชันนี้ "คืนค่าเป็น int กลับมา" ต้องมีตัวแปรมารับผล
        int totalDamage = CalculateDamage(baseDamage: 10, hits: 3);
        Debug.Log($"ดาเมจรวม = {totalDamage}");

        // เรียกใช้ตรง ๆ ใน Debug.Log ก็ได้ ไม่ต้องมีตัวแปรมารับก็ได้ถ้าไม่เก็บไว้ใช้ต่อ
        Debug.Log($"เกราะกันได้กี่ % = {CalculateDefensePercent(currentArmor: 40, maxArmor: 100)}");
    }


    // ---------- ฟังก์ชันที่ประกาศไว้ใช้เอง ----------

    // void = ไม่คืนค่าอะไรกลับ, ไม่มี () ว่าง = ไม่รับ parameter
    void SayHello()
    {
        Debug.Log("สวัสดี จากฟังก์ชัน SayHello");
    }

    // void แต่รับ parameter ชื่อ amount ชนิด int เข้ามา
    // ตอนเรียกใช้ต้องใส่ตัวเลขในวงเล็บ เช่น Heal(30)
    void Heal(int amount)
    {
        Debug.Log($"ฮีลไป {amount} หน่วย");
    }

    // int ก่อนชื่อฟังก์ชัน = ฟังก์ชันนี้ "ต้อง" คืนค่าเป็น int กลับไปให้คนเรียก
    // รับ 2 parameter คั่นด้วย , และ return คือคำสั่งส่งค่ากลับ (ฟังก์ชันจบทันทีที่เจอ return)
    int CalculateDamage(int baseDamage, int hits)
    {
        int total = baseDamage * hits;
        return total;               // ส่งค่าใน total กลับไปให้บรรทัดที่เรียกใช้
    }

    // float = คืนค่ากลับเป็นทศนิยม
    // *** จุดสำคัญ: ต้อง cast เป็น float ก่อนหาร ไม่งั้นจะเจอบั๊กแบบข้อสอบที่พลาดไป ***
    float CalculateDefensePercent(int currentArmor, int maxArmor)
    {
        float percent = (float)currentArmor / maxArmor * 100f;
        return percent;
    }


    // ============================================================
    //  แบบฝึกหัด — ลองแก้เองทีละข้อ แล้วกด Play ดู Console ทุกครั้ง
    // ------------------------------------------------------------
    //  ข้อ 1 (ง่าย)  เรียก SayHello() ซ้ำอีก 2 รอบใน Start() ดูว่า Console
    //                พิมพ์คำว่า "สวัสดี" กี่ครั้ง
    //
    //  ข้อ 2 (ง่าย)  ลองเรียก Heal(100) เพิ่มอีกบรรทัด แล้วดูผลใน Console
    //
    //  ข้อ 3 (กลาง)  เขียนฟังก์ชันใหม่เอง ชื่อ Add
    //                รับ parameter 2 ตัว (int x, int y) คืนค่าเป็น int ผลบวก
    //                แล้วเรียกใช้ใน Start() ด้วย Debug.Log(Add(3, 4));
    //
    //  ข้อ 4 (กลาง)  เขียนฟังก์ชัน IsDead รับ int hp เข้ามา
    //                คืนค่าเป็น bool (hp <= 0 คือ true)
    //                ใบ้โครงฟังก์ชัน:
    //                    bool IsDead(int hp)
    //                    {
    //                        return hp <= 0;
    //                    }
    //
    //  ข้อ 5 (ยาก)   แก้ CalculateDamage ให้รับ parameter เพิ่มอีกตัวชื่อ
    //                bool isCritical แล้วถ้า isCritical เป็น true ให้ผลคูณ 2 เท่า
    //                ก่อน return (ใบ้: ใช้ if ข้างในฟังก์ชันได้เลย)
    // ============================================================
}
