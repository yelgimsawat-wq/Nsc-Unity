using UnityEngine;

// ============================================================
//  บทที่ 1 : พื้นฐาน C# ใน Unity
// ------------------------------------------------------------
//  วิธีใช้ไฟล์นี้:
//   1. ใน Unity เปิดซีนอะไรก็ได้ (ซีนเปล่าก็ได้)
//   2. เมนู GameObject > 3D Object > Cube  (จะได้กล่องมาหนึ่งใบ)
//   3. คลิก Cube แล้วลากไฟล์ Lesson01_Basics.cs ไปวางใน Inspector
//   4. กด Play แล้วดูหน้าต่าง Console (เมนู Window > General > Console)
// ============================================================

public class Lesson01_Basics : MonoBehaviour
{
    // ---------- ส่วนที่ 1 : ตัวแปร (variable) ----------
    // ตัวแปร = กล่องเก็บค่า  เขียนว่า  [ชนิด] [ชื่อ] = [ค่า];
    //
    // public = โผล่ให้แก้ได้ใน Inspector ของ Unity โดยไม่ต้องแก้โค้ด
    // ลองกด Play แล้วแก้เลขใน Inspector สด ๆ ดู จะเห็นผลทันที

    public float speed = 50f;        // float  = เลขทศนิยม  (ต้องมี f ต่อท้าย)
    public int   score = 0;          // int    = เลขจำนวนเต็ม
    public string playerName = "Nok";// string = ข้อความ    (ต้องมี " ครอบ)
    public bool  canRotate = true;   // bool   = จริง/เท็จ  (true / false)


    // ---------- ส่วนที่ 2 : ฟังก์ชัน Start() ----------
    // Unity เรียกฟังก์ชันนี้ "ครั้งเดียว" ตอนกด Play
    // เหมาะกับการตั้งค่าเริ่มต้น
    void Start()
    {
        // Debug.Log = สั่งพิมพ์ข้อความออก Console — เครื่องมือสำคัญที่สุดของมือใหม่
        Debug.Log("เริ่มเกมแล้ว!");

        // $"..." คือการเอาค่าตัวแปรมาแทรกในข้อความ (ใส่ตัวแปรใน { })
        Debug.Log($"ผู้เล่นชื่อ {playerName} ความเร็ว {speed}");

        // if = ถ้า... ให้ทำ...   (เงื่อนไขต้องได้ผลเป็น true/false)
        if (speed > 100f)
        {
            Debug.Log("เร็วมาก!");
        }
        else
        {
            Debug.Log("ความเร็วปกติ");
        }

        // for = วนซ้ำ  อ่านว่า "เริ่ม i=0, ทำไปเรื่อย ๆ ตราบใดที่ i<3, แต่ละรอบ i เพิ่ม 1"
        for (int i = 0; i < 3; i++)
        {
            score = score + 10;      // เขียนสั้น ๆ ได้ว่า  score += 10;
            Debug.Log($"รอบที่ {i} คะแนน = {score}");
        }
    }


    // ---------- ส่วนที่ 3 : ฟังก์ชัน Update() ----------
    // Unity เรียกฟังก์ชันนี้ "ทุกเฟรม" (ประมาณ 60 ครั้งต่อวินาที)
    // เหมาะกับการรับ input และการเคลื่อนไหว
    void Update()
    {
        // return = ออกจากฟังก์ชันทันที ไม่ทำบรรทัดที่เหลือ
        // ! อ่านว่า "ไม่"  ดังนั้น !canRotate = "ถ้า canRotate ไม่จริง"
        if (!canRotate) return;

        // transform = ตำแหน่ง/การหมุน/ขนาด ของ GameObject ที่สคริปต์นี้เกาะอยู่
        // Time.deltaTime = เวลาที่ผ่านไปตั้งแต่เฟรมที่แล้ว
        //   *** คูณด้วยค่านี้เสมอเวลาเคลื่อนไหวใน Update ***
        //   ไม่งั้นคอมพิวเตอร์เร็ว/ช้าจะหมุนไม่เท่ากัน
        transform.Rotate(0f, speed * Time.deltaTime, 0f);

        // รับ input จากคีย์บอร์ด: กด Space แล้วบวกคะแนน
        if (Input.GetKeyDown(KeyCode.Space))
        {
            score += 1;
            Debug.Log($"กด Space! คะแนน = {score}");
        }
    }


    // ============================================================
    //  แบบฝึกหัด — ลองแก้เองทีละข้อ แล้วกด Play ดูผลทุกครั้ง
    // ------------------------------------------------------------
    //  ข้อ 1 (ง่าย)  เปลี่ยน speed เป็น 200 แล้วดูว่ากล่องหมุนต่างไปยังไง
    //                จากนั้นลองแก้ค่าใน Inspector ตอน Play อยู่
    //
    //  ข้อ 2 (ง่าย)  เพิ่มตัวแปร  public float scale = 1f;
    //                แล้วใน Start() เขียน  transform.localScale = Vector3.one * scale;
    //
    //  ข้อ 3 (กลาง)  ทำให้กด S แล้วสลับ canRotate ระหว่าง true/false
    //                ใบ้:  canRotate = !canRotate;
    //
    //  ข้อ 4 (กลาง)  ทำให้ score ถึง 5 แล้วพิมพ์ "ชนะ!" ออก Console แค่ครั้งเดียว
    //                ใบ้: ต้องมีตัวแปร bool อีกตัวจำไว้ว่าพิมพ์ไปแล้ว
    //
    //  ข้อ 5 (ยาก)   ทำให้กล่องขยับขึ้นลงเป็นคลื่น
    //                ใบ้:  transform.position = new Vector3(0f, Mathf.Sin(Time.time), 0f);
    // ============================================================
}
